// Smart non-repeating queue to guarantee truly random, fresh paragraphs every single time!
let recentPassageIds: string[] = [];

export function getRandomPassage(excludeId?: string): TypingPassage {
  // Try loading recent history from sessionStorage if available in browser
  try {
    if (typeof window !== 'undefined' && recentPassageIds.length === 0) {
      const stored = sessionStorage.getItem('surtype_recent_passages');
      if (stored) {
        recentPassageIds = JSON.parse(stored);
      }
    }
  } catch {
    // Ignore storage errors
  }

  // Filter pool to avoid repeating recently shown passages
  const pool = TYPING_PASSAGES.filter(p => {
    if (excludeId && p.id === excludeId) return false;
    return !recentPassageIds.includes(p.id);
  });

  let chosen: TypingPassage;

  if (pool.length > 0) {
    const randomIndex = Math.floor(Math.random() * pool.length);
    chosen = pool[randomIndex];
  } else {
    // Reset queue when most have been shown
    recentPassageIds = excludeId ? [excludeId] : [];
    const fallbackPool = excludeId ? TYPING_PASSAGES.filter(p => p.id !== excludeId) : TYPING_PASSAGES;
    const randomIndex = Math.floor(Math.random() * fallbackPool.length);
    chosen = fallbackPool[randomIndex];
  }

  // Record this passage to recent history (keeping last 15)
  recentPassageIds.push(chosen.id);
  if (recentPassageIds.length > 15) {
    recentPassageIds.shift();
  }

  try {
    if (typeof window !== 'undefined') {
      sessionStorage.setItem('surtype_recent_passages', JSON.stringify(recentPassageIds));
    }
  } catch {
    // Ignore storage errors
  }

  return chosen;
}
